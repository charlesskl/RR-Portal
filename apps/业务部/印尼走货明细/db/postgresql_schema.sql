    CONSTRAINT fk_shipment_items_shipment
        FOREIGN KEY (shipment_id) REFERENCES dbo.shipments(id) ON DELETE CASCADE,
    CONSTRAINT fk_shipment_items_material
        FOREIGN KEY (material_id) REFERENCES dbo.materials(id),
    CONSTRAINT fk_shipment_items_outbound
        FOREIGN KEY (outbound_id) REFERENCES dbo.outbound(id)
);
ALTER TABLE dbo.shipment_items ADD COLUMN IF NOT EXISTS outbound_id INTEGER;
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_shipment_items_outbound'
          AND conrelid = 'dbo.shipment_items'::regclass
    ) THEN
        ALTER TABLE dbo.shipment_items
            ADD CONSTRAINT fk_shipment_items_outbound
            FOREIGN KEY (outbound_id) REFERENCES dbo.outbound(id);
    END IF;
END $$;
CREATE INDEX IF NOT EXISTS ix_shipment_items_shipment ON dbo.shipment_items(shipment_id);
CREATE INDEX IF NOT EXISTS ix_shipment_items_po_no ON dbo.shipment_items(po_no);
CREATE INDEX IF NOT EXISTS ix_shipment_items_outbound ON dbo.shipment_items(outbound_id);

CREATE TABLE IF NOT EXISTS dbo.audit_logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at     TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL
                    DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    user_id         INTEGER,
    username        VARCHAR(64) NOT NULL DEFAULT '',
    module          VARCHAR(32) NOT NULL,
    action          VARCHAR(32) NOT NULL,
    entity_type     VARCHAR(64) NOT NULL,
    entity_id       VARCHAR(64) NOT NULL DEFAULT '',
    summary         VARCHAR(512) NOT NULL DEFAULT '',
