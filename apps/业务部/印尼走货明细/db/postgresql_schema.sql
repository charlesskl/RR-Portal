    currency            VARCHAR(8) NOT NULL DEFAULT '¥',
    po_no               VARCHAR(64),
    po_date             DATE,
    supplier            VARCHAR(256),
    customs_company     VARCHAR(256),
    bl_head             VARCHAR(256),
    contract_no         VARCHAR(64),
    contract_date       DATE,
    invoice_no          VARCHAR(64),
    invoice_date        DATE,
    invoice_price       NUMERIC(18,4),
