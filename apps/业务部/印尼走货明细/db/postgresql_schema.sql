CREATE INDEX IF NOT EXISTS ix_audit_logs_entity ON dbo.audit_logs(entity_type, entity_id);
CREATE INDEX IF NOT EXISTS ix_audit_logs_user ON dbo.audit_logs(user_id, occurred_at DESC);

CREATE TABLE IF NOT EXISTS dbo.settings (
    "key"       VARCHAR(128) NOT NULL PRIMARY KEY,
    value       TEXT,
    updated_at  TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL
                DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
